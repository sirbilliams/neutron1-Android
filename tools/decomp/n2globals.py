#!/usr/bin/env python3
"""Negatron globals the retargeted code still uses but Neutron.exe's data section has no address for
yet (tools/decomp/retarget.py left them as `g_N2_xxxxxx`, or global_types marks the name
"unresolved (Neutron2 address)").

Until each is found in Neutron.exe they live in a separate zero-filled block shaped like
Neutron2.exe's data section, with Negatron's typed views, so names that share an address (or
overlap) in the original still do here:

    neg::g_n2_data[]   Neutron2.exe's data section layout, zero at start (port: no initial values!)
    neg::g_n2_ptrs[]   one pointer slot per 4-byte word of it

    #define g_N2_545e78  (*(C2DInGameMenu* *)&neg::g_n2_ptrs[0x4f9e])    unnamed (retarget.py)
    #define g_menu       (*(C2DInGameMenu* *)&neg::g_n2_ptrs[0x4f9e])    named, unresolved

A name defined by gen/globals.h (resolved: in global_types with a Neutron.exe address) or declared
`extern` in a hand-written file is never emitted, so resolving a global removes it from here.

    n2globals.py <Negatron gen/globals.h> game/src  ->  game/src/gen/n2globals.h, n2globals.cpp
"""
import os, re, sys

def main():
    n2h, src = sys.argv[1:3]
    n2 = {}; classes = []
    for line in open(n2h):
        m = re.match(r'#define (g_\w+) (.*)$', line.rstrip('\n'))
        if m: n2[m.group(1)] = m.group(2).split('\t//')[0].strip()
        m = re.match(r'class (\w+);', line)
        if m: classes.append(m.group(1))
    m = re.search(r'DATA_SIZE = (0x[0-9a-f]+)', open(n2h).read()); size = m.group(1)
    defined = set()
    for line in open(os.path.join(src, 'gen', 'globals.h')):
        m = re.match(r'#define (g_\w+)', line)
        if m: defined.add(m.group(1))
    used = set()
    for root, _, files in os.walk(src):
        if os.path.basename(root) == 'gen': continue
        for fn in files:
            if not fn.endswith(('.h', '.cpp', '.inc')): continue
            t = open(os.path.join(root, fn), errors='replace').read()
            for m in re.finditer(r'\bextern\s[^;(]*?\b(g_\w+)\s*(?:\[[^\]]*\])*\s*;', t): defined.add(m.group(1))
            for m in re.finditer(r'\b(g_\w+)\b', t): used.add(m.group(1))
    alias = {}
    for line in open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'n2_aliases.txt')):
        f = line.split('#')[0].split()
        if len(f) == 2 and f[1] in defined: alias[int(f[0], 16)] = f[1]
    n2addr = {}
    for k, v in n2.items():
        m = re.search(r'g_(data|ptrs)\[(0x[0-9a-f]+)\]', v)
        if m: n2addr[k] = 0x4ec000 * 0 + int(m.group(2), 16) * (4 if m.group(1) == 'ptrs' else 1)
    base = int(re.search(r'DATA_BASE = (0x[0-9a-f]+)', open(n2h).read()).group(1), 16)
    out = []
    for name in sorted(used):
        if name not in defined and name in n2addr and base + n2addr[name] in alias:
            out.append('#define %s %s\t// Neutron.exe global (n2_aliases.txt)' % (name, alias[base + n2addr[name]]))
            continue
        if name in defined or re.match(r'g_[0-9a-f]{6}$', name): continue
        if name.startswith('g_N2_'):
            e = n2.get('g_' + name[5:])
            if int(name[5:], 16) in alias:
                out.append('#define %s %s\t// Neutron.exe global (n2_aliases.txt)' % (name, alias[int(name[5:], 16)]))
                continue
        else:
            e = n2.get(name)
        if not e: continue
        e = e.replace('neg::g_data[', 'neg::g_n2_data[').replace('neg::g_ptrs[', 'neg::g_n2_ptrs[')
        m = re.search(r'g_n2_(data|ptrs)\[(0x[0-9a-f]+)\]', e)
        off = int(m.group(2), 16) * (4 if m.group(1) == 'ptrs' else 1) if m else 1 << 30
        out.append('#define %s %s%s' % (name, e, '\t// initialised in Neutron2.exe: port gets 0' if off < 0x10000 else ''))
    h = ['// generated by tools/decomp/n2globals.py - Negatron globals not located in Neutron.exe yet (TODO(BG))',
         '#pragma once', '#include <stddef.h>'] + ['class %s;' % c for c in classes] + [
         'namespace neg {', 'enum { N2_DATA_SIZE = %s };' % size,
         'extern unsigned char g_n2_data[N2_DATA_SIZE];		// zero at start (Neutron2.exe\'s initial values are not used)',
         'extern void *g_n2_ptrs[N2_DATA_SIZE / 4];', '}', ''] + out
    open(os.path.join(src, 'gen', 'n2globals.h'), 'w').write('\n'.join(h) + '\n')
    c = ['// generated by tools/decomp/n2globals.py - see n2globals.h', '#include "n2globals.h"', 'namespace neg {',
         'unsigned char g_n2_data[N2_DATA_SIZE] __attribute__((aligned(16)));', 'void *g_n2_ptrs[N2_DATA_SIZE / 4];', '}']
    open(os.path.join(src, 'gen', 'n2globals.cpp'), 'w').write('\n'.join(c) + '\n')
    print('%d Negatron globals still unresolved' % len(out))

main()
